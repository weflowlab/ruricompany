/** 차량 카드 한 장에 필요한 데이터 */
export type Vehicle = {
  /** React key 용 고유 id */
  id: string;
  /** 차량 분류 — 카드 좌상단 뱃지로 노출 */
  category: "소형" | "중형" | "대형" | "특장";
  /** 모델명 (예: 포터2) */
  model: string;
  /** 세부 트림/사양 (예: 초장축 슈퍼캡 스마트) */
  trim: string;
  /**
   * 한 줄 설명. 어떤 용도에 맞는 차인지 서술한다.
   * 금액 관련 표현은 넣지 않는다.
   */
  summary: string;
  /** 썸네일 자리 표시용 한국어 라벨 */
  imageLabel: string;
};

