/**
 * services.ts — 서비스(구매 방식) 소개 데이터
 *
 * 왜 있나
 *  구글폼 6번에서 "서비스/제품 소개" 섹션을 요청했고,
 *  3번 업종이 "신차할부 / 신차장기렌트 / 신차리스" 3종이므로
 *  이 3가지를 비교해서 보여 주는 섹션이 필요하다.
 *  ServiceSection 컴포넌트가 이 배열을 받아 3열 비교 카드를 그린다.
 *
 * 소비처
 *  - ServiceSection : 3열 비교 카드
 *  - ConsultForm    : "관심 상품" 선택지 (plan.name 만 사용)
 *
 * ----------------------------------------------------------------------------
 * ★ 경량화 (2026-07-30)
 * ----------------------------------------------------------------------------
 * 섹션을 한 번 삭제했다가 되살리면서, 원인이었던 "무거움"을 데이터 단계에서 걷어냈다.
 *
 *  [삭제] description (2~3문장) → `summary` 한 문장으로 대체.
 *         카드에서 가장 길어 높이를 밀어 올리던 항목이다.
 *  [축소] features 4개 → 3개. 카드가 "세 가지 방법"이니 근거도 3개로 맞췄다.
 *  [삭제] tone       — 파스텔 3색(민트/크림/라벤더) 구분을 그만두면서 쓸 곳이 없어졌다.
 *         색은 블루 계열 하나로 통일한다. 자세한 배경은 globals.css 컬러 토큰 주석 참고.
 *  [삭제] imageLabel — 카드 상단의 128px 아이콘 자리(Placeholder)를 없앴다.
 *         회색 이미지 자리 3개가 나란히 놓이는 것이 조잡함(구글폼 8-1)의 주원인이었다.
 *
 * 설계 원칙 (구글폼 8-1: "조잡하거나 금액 노출" 회피)
 *  - 금액·이자율·월 납입금 같은 숫자를 일절 넣지 않는다.
 *    구매 방식의 "성격"과 "이런 분께 맞다"만 서술한다.
 *  - summary 는 한 문장, features 는 3개로 **모든 카드가 같은 개수**를 지킨다.
 *    (개수가 다르면 카드 높이가 어긋나고, 높이가 안 맞는 카드는 조잡해 보인다)
 */

/** 서비스(구매 방식) 카드 한 장에 필요한 데이터 */
export type ServicePlan = {
  /** React key 용 고유 id */
  id: string;
  /** 서비스명 (예: 신차 할부) — ConsultForm 의 "관심 상품" 선택지로도 쓰인다 */
  name: string;
  /** 카드 상단에 붙는 짧은 한 줄 요약 */
  tagline: string;
  /** 카드 본문. **한 문장**으로 제한한다 (카드 높이 정렬 + 경량화) */
  summary: string;
  /** 특징 3개. 카드마다 개수를 맞춰 높이를 정렬한다 */
  features: string[];
  /** "이런 분께 맞습니다" 한 줄 */
  bestFor: string;
  /**
   * 카드 상단 이미지 경로 (2026-07-31 실사진 적용).
   * public/services/ 아래 01~03 이 이 배열 순서와 1:1로 대응한다.
   * next/image 의 src 로 넘어가므로 `/` 로 시작하는 절대 경로여야 한다.
   */
  image: string;
  /** 이미지 대체 텍스트. 카드의 name/summary 를 반복하지 않고 장면만 짧게 적는다 */
  imageAlt: string;
};

