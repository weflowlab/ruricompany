/**
 * process.ts — 이용 절차 5단계 더미 데이터
 *
 * 역할
 *  - ProcessSection 이 스크롤 진입 시 순차(stagger) 등장시키는 5개 스텝 카드를 제공한다.
 *  - 데스크톱에서는 가로 5칸, 모바일에서는 세로 목록으로 배치된다.
 *
 * 클라이언트 요청사항(구글폼) 반영 내역
 *  - 3번  업종        → 화물차 상담 흐름("적재 조건", "특장 제작")을 신차 구매 흐름으로 바꿨다.
 *                       상담 신청 → 조건 비교·심사 → 방식 결정·계약 → 출고·인도 → 사후 관리
 *  - 8-1번 금액 노출 금지 → 3단계에 있던 "선수금·계약 기간을 바꿔 가며 월 납입금 비교" 문구를
 *                       "조건을 나란히 비교"로 바꿔 금액을 떠올리게 하는 표현을 없앴다.
 *  - 8-1번 조잡함 회피   → description 을 모두 한 줄(30자 내외)로 맞췄다.
 *                       데스크톱에서 5칸으로 쪼개질 때 설명 길이가 들쭉날쭉하면
 *                       카드 높이가 어긋나 조잡해 보이므로 길이를 의도적으로 통일했다.
 *  - 18번 선호 연락 방법 → 1단계 안내에서 "문자"를 빼고 전화·카카오톡만 언급한다.
 *
 * 주의
 *  - step 번호는 1부터 시작하며 화면에서 "STEP 01" 형태로 0 패딩해 표시한다.
 */

/** 이용 절차 한 단계 */
export type ProcessStep = {
  /** 단계 번호 (1~5). React key 로도 사용 가능 */
  step: number;
  /** 단계 제목 (짧게) */
  title: string;
  /** 단계 설명 — 한 줄(30자 내외)로 통일한다 */
  description: string;
};

